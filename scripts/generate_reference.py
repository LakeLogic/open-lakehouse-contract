def _with_block(text: str, reference: str, start: str = START, end: str = END) -> str:
    block = f"{start}\n{reference.rstrip()}\n{end}"
    if start in text and end in text:
        head, rest = text.split(start, 1)
        _, tail = rest.split(end, 1)
        return head + block + tail
    return text.rstrip() + "\n\n" + block + "\n"


def _cell(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ").strip()


def build_recipes() -> str:
    """The Core playbook: one section per recipe in recipes/ — when to use it, the contract, every
    value a person sets (format, example, secret, where), and what to do before the first run.
    Generated, like the reference, so an agent is never taught a recipe that no longer holds."""
    import yaml

    recipes = [
        yaml.safe_load(p.read_text(encoding="utf-8"))
        for p in sorted(RECIPES_DIR.rglob("*.yaml"))
    ]
    if not recipes:
        return ""
    out = [
        "# LakeLogic Core playbook — recipes",
        "",
        "Generated from `recipes/` by `scripts/generate_reference.py`. Each recipe is a contract that",
        "LakeLogic Core runs, proven against real systems. Copy the contract, then fill in every",
        "`{parameter}`. Secrets are NEVER written into a contract: use `env:VAR` (or a key vault reference).",
        "",
        "| Recipe | Group | Use when |",
        "|---|---|---|",
    ]
    out += [
        f"| {_cell(r['title'])} | {r['group']} | {_cell(r['when'])} |" for r in recipes
    ]
    for r in recipes:
        out += [
            "",
            f"## {r['title']}",
            "",
            f"`{r['id']}` · {r['group']} · load patterns: "
            + ", ".join(r.get("load_patterns") or []),
            "",
            _cell(r["when"]),
            "",
            "```yaml",
            yaml.safe_dump(r["contract"], sort_keys=False, allow_unicode=True).rstrip(),
            "```",
            "",
            "| Parameter | What it is | Expected format | Example | Secret | Set in |",
            "|---|---|---|---|---|---|",
        ]
        for p in r["parameters"]:
            out.append(
                f"| `{p['name']}` | {_cell(p['what'])} | `{_cell(p['format'])}` | "
                f"`{_cell(p['examples'][0])}` | {'yes' if p['secret'] else 'no'} | {_cell(p['set_in'])} |"
            )
        out += ["", "**Before you run**", ""] + [
            f"- {_cell(b)}" for b in r["before_you_run"]
        ]
        out += ["", f"**What a design-time test proves:** {_cell(r['studio_test'])}"]
    return "\n".join(out) + "\n"


def planned_writes(schema: dict) -> dict[Path, str]:
    reference = build_reference(schema)
    guide = build_guide(schema)
    recipes = build_recipes()
    # The Claude skill folder carries the full tables as a file of its own (skills load extra
    # files on demand), so `olc init --tool claude` installs them beside SKILL.md.
    writes = {REFERENCE_PATH: reference, ROOT / "skills/claude/skills/olc/olc-reference.md": reference}
    if recipes:
        writes[RECIPES_PATH] = recipes
    for rel in CONTEXT_FILES:
        path = ROOT / rel
        if path.exists():
            text = _with_block(path.read_text(encoding="utf-8"), guide)
            if recipes:
                text = _with_block(text, recipes, RECIPES_START, RECIPES_END)
            writes[path] = text
    return writes


def stale(schema: dict) -> list[Path]:
    return [
        p
        for p, text in planned_writes(schema).items()
        if not p.exists() or p.read_text(encoding="utf-8") != text
    ]


def main(argv: list[str]) -> int:
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    if "--check" in argv:
        bad = stale(schema)
        for p in bad:
            print(f"stale: {p.relative_to(ROOT)}")
        return 1 if bad else 0
    changed = 0
    for path, text in planned_writes(schema).items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8", newline="\n")
            changed += 1
            print(f"updated {path.relative_to(ROOT)}")
    print(f"OLC reference: {changed} file(s) updated")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
